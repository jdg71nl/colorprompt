#!/bin/bash
#= kiosk-setup.sh

# d260922 jdg https://claude.ai/chat/8baa7f65-4d9e-4e58-b079-39ca3bdcd1c4

# Idempotent setup script for an Alpine Linux kiosk on Raspberry Pi.
#
# Stack: seatd + greetd → cage (Wayland) → firefox --kiosk
# Runs under the CURRENT user (whoami) — do NOT run with sudo.
# The script uses sudo internally where root privileges are needed.
#
# Usage (as normal user with sudo access):
#   bash kiosk-setup.sh
#
# Prerequisites:
#   - Alpine Linux 3.24 sys-mode (persistent filesystem)
#   - Community repo enabled (or let step 1 do it)
#   - Your web app already running and reachable at KIOSK_URL
#   - Current user has passwordless sudo access
#=

set -e

# ── Config ────────────────────────────────────────────────────────────────────

KIOSK_URL="http://127.0.0.1:8084"
KIOSK_USER="$(whoami)"
KIOSK_HOME="$(eval echo ~"$KIOSK_USER")"

# ── Sanity checks ─────────────────────────────────────────────────────────────

if [ "$(id -u)" -eq 0 ]; then
  echo "ERROR: do not run this script as root or with sudo." >&2
  echo "       Run as your normal user: bash $0" >&2
  exit 1
fi

echo "==> Checking sudo access..."
if ! sudo -n true 2>/dev/null; then
  echo "ERROR: $KIOSK_USER does not have passwordless sudo access." >&2
  echo "       Add to /etc/sudoers.d/: $KIOSK_USER ALL=(ALL) NOPASSWD: ALL" >&2
  exit 1
fi
echo "    OK — sudo access confirmed for $KIOSK_USER"

echo ""
echo "==> Kiosk setup"
echo "    User:      $KIOSK_USER (home: $KIOSK_HOME)"
echo "    Kiosk URL: $KIOSK_URL"
echo ""

# ── 1. Ensure community repo is enabled ───────────────────────────────────────

echo "==> [1/7] Checking APK community repository..."
if grep -q '^#.*community' /etc/apk/repositories; then
  sudo sed -i '/community/s/^#//' /etc/apk/repositories
  echo "    Enabled community repo."
else
  echo "    Community repo already enabled."
fi

# ── 2. Install packages ───────────────────────────────────────────────────────

echo "==> [2/7] Installing packages..."
sudo apk update -q

sudo apk add --no-progress \
  util-linux \
  eudev \
  shadow-subids \
  wayland \
  mesa-dri-gallium \
  mesa-egl \
  mesa-gbm \
  libdrm \
  seatd \
  seatd-openrc \
  cage \
  libinput \
  greetd \
  firefox \
  font-dejavu

echo "    Done."

# ── 3. Add user to required groups ───────────────────────────────────────────

echo "==> [3/7] Checking group memberships for $KIOSK_USER..."
for group in seat video input; do
  if ! getent group "$group" > /dev/null 2>&1; then
    echo "    WARNING: group '$group' does not exist, skipping."
    continue
  fi
  if id -nG "$KIOSK_USER" | grep -qw "$group"; then
    echo "    Already in: $group"
  else
    sudo addgroup "$KIOSK_USER" "$group"
    echo "    Added to:   $group"
  fi
done

# ── 4. Enable OpenRC services ─────────────────────────────────────────────────

echo "==> [4/7] Enabling OpenRC services..."
for svc_runlevel in "udev:sysinit" "seatd:boot" "greetd:default"; do
  svc="${svc_runlevel%%:*}"
  runlevel="${svc_runlevel##*:}"
  if sudo rc-update show "$runlevel" 2>/dev/null | grep -qw "$svc"; then
    echo "    Already enabled: $svc @ $runlevel"
  else
    sudo rc-update add "$svc" "$runlevel"
    echo "    Enabled:         $svc @ $runlevel"
  fi
done

# ── 5. Configure greetd ───────────────────────────────────────────────────────

echo "==> [5/7] Configuring greetd..."
sudo mkdir -p /etc/greetd

sudo tee /etc/greetd/config.toml > /dev/null << EOF
[terminal]
vt = 1

[default_session]
command = "$KIOSK_HOME/start-kiosk.sh"
user = "$KIOSK_USER"
EOF
echo "    Written: /etc/greetd/config.toml"

# ── 6. Create the kiosk launch script ────────────────────────────────────────

echo "==> [6/7] Writing kiosk launch script..."
cat > "$KIOSK_HOME/start-kiosk.sh" << EOF
#!/bin/sh
#= $KIOSK_HOME/start-kiosk.sh
# Auto-generated by kiosk-setup.sh

export XDG_RUNTIME_DIR="/tmp/kiosk-runtime-\$(id -u)"
mkdir -p "\$XDG_RUNTIME_DIR"
chmod 0700 "\$XDG_RUNTIME_DIR"

# wlroots: use legacy DRM modesetting (atomic can fail on some panels)
export WLR_DRM_NO_ATOMIC=1
# wlroots: don't fail if no input devices present at compositor start
export WLR_LIBINPUT_NO_DEVICES=1
# wlroots: force DRM backend (don't attempt headless or x11 fallback)
export WLR_BACKENDS=drm
# wlroots: set the render backend explicitly
export WLR_RENDERER=gles2

# Wait for seatd to be ready and DRM device to appear
until [ -e /dev/dri/card0 ]; do
    sleep 1
done
# Extra settle time for seatd
sleep 2

# Recreate a clean Firefox profile on every boot.
# Prevents "profile missing or inaccessible" after unclean shutdowns.
rm -rf "$KIOSK_HOME/.mozilla"
mkdir -p "$KIOSK_HOME/.mozilla/firefox/kiosk"
touch    "$KIOSK_HOME/.mozilla/firefox/kiosk/times.json"
touch    "$KIOSK_HOME/.mozilla/firefox/kiosk/prefs.js"

cat > "$KIOSK_HOME/.mozilla/firefox/profiles.ini" << 'PROFILES'
[General]
StartWithLastProfile=0

[Profile0]
Name=kiosk
IsRelative=1
Path=kiosk
Default=1
PROFILES

cat > "$KIOSK_HOME/.mozilla/firefox/installs.ini" << 'INSTALLS'
[Install]
Default=kiosk
Locked=1
INSTALLS

exec cage -- firefox --kiosk --no-remote \\
    --profile "$KIOSK_HOME/.mozilla/firefox/kiosk" \\
    "$KIOSK_URL"
EOF

chmod +x "$KIOSK_HOME/start-kiosk.sh"
echo "    Written: $KIOSK_HOME/start-kiosk.sh"

# ── 7. Configure /boot/usercfg.txt for KMS/GPU ───────────────────────────────

echo "==> [7/7] Checking /boot/usercfg.txt..."
add_if_missing() {
  local line="$1"
  if grep -qF "$line" /boot/usercfg.txt 2>/dev/null; then
    echo "    Already present: $line"
  else
    echo "$line" | sudo tee -a /boot/usercfg.txt > /dev/null
    echo "    Added:           $line"
  fi
}
add_if_missing "dtoverlay=vc4-kms-v3d"
add_if_missing "gpu_mem=128"

# ── Done ──────────────────────────────────────────────────────────────────────

echo ""
echo "================================================================"
echo " Kiosk setup complete."
echo ""
echo "   User:          $KIOSK_USER"
echo "   Launch script: $KIOSK_HOME/start-kiosk.sh"
echo "   Kiosk URL:     $KIOSK_URL"
echo ""
echo " Reboot to start the kiosk:  reboot"
echo ""
echo " Boot sequence:"
echo "   OpenRC → eudev, seatd, greetd"
echo "   greetd autologins $KIOSK_USER → start-kiosk.sh"
echo "   cage (Wayland) → firefox --kiosk $KIOSK_URL"
echo "================================================================"

#-eof
