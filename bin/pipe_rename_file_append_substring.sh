#!/usr/bin/env bash
#= bin/pipe_rename_file_append_substring.sh
#= /Users/jdg/colorprompt/bin/pipe_rename_file_append_substring.sh

# d261115 jdg Claude Code:
# pipe_rename_file_append_substring.sh
#
# Reads a list of files (one per line) from stdin and renames each one by
# adding the substring given as $1 to its filename -- but only if the
# filename does not already contain that substring.
#
# Two modes, chosen by the first character of the substring:
#   - starts with a dot (.)  -> appended after the extension (at the very end)
#       report.txt  ->  report.txt.bak
#   - anything else          -> inserted before the (last) extension
#       report.txt  ->  report_done.txt
#       README      ->  README_done          (no extension)
#       .bashrc     ->  .bashrc_done         (leading dot is not an extension)
#       a.tar.gz    ->  a.tar_done.gz        (only the last extension counts)
#
# Input lines may be bare filenames or paths (relative or absolute). Only the
# filename part (basename) is checked and changed; the file stays in its
# directory.
#
# Usage:
#   ls -1 *somekey* | pipe_rename_file_append_substring.sh _done
#   find . -name '*.log' | pipe_rename_file_append_substring.sh .bak

set -u

if [ $# -ne 1 ] || [ -z "$1" ]; then
    cat<<EOF >&2
# Usage: <command listing files> | $(basename "$0") <substring>
# e.g.
#        ls -1 *somekey* | pipe_rename_file_append_substring.sh _done
#        find . -name '*.log' | pipe_rename_file_append_substring.sh .bak
EOF
    exit 1
fi

substring="$1"
status=0
renamed=0

# Undo script: created on the first successful rename, with absolute paths
# so it can be run from any directory.
undo="/tmp/undo_pipe_rename_$(date +%Y%m%d_%H%M%S)_$$.sh"

abspath() {
    case "$1" in
        /*) printf '%s' "$1" ;;
        *)  printf '%s' "$PWD/${1#./}" ;;
    esac
}

add_undo() {   # $1 = original name, $2 = new name
    if [ $renamed -eq 0 ]; then
        cat > "$undo" <<'EOF'
#!/usr/bin/env bash
# Undo script generated by pipe_rename_file_append_substring.sh
undo_mv() {   # $1 = current (renamed) name, $2 = original name
    if [ ! -e "$1" ]; then
        echo "skip: '$1' no longer exists" >&2
    elif [ -e "$2" ]; then
        echo "skip: '$2' already exists" >&2
    elif mv -- "$1" "$2"; then
        echo "restored: '$1' -> '$2'"
    fi
}
EOF
        chmod +x "$undo"
    fi
    printf 'undo_mv %q %q\n' "$(abspath "$2")" "$(abspath "$1")" >> "$undo"
    renamed=$((renamed + 1))
}

while IFS= read -r file || [ -n "$file" ]; do
    [ -z "$file" ] && continue

    if [ ! -e "$file" ]; then
        echo "skip: '$file' does not exist" >&2
        status=1
        continue
    fi

    # Split into directory and filename (handles bare names and paths)
    case "$file" in
        */*) dir="${file%/*}/"; name="${file##*/}" ;;
        *)   dir="";            name="$file" ;;
    esac

    if [ -z "$name" ]; then
        echo "skip: '$file' has no filename part" >&2
        continue
    fi

    case "$name" in
        *"$substring"*)
            echo "skip: '$file' already contains '$substring'"
            continue
            ;;
    esac

    case "$substring" in
        .*)
            # Dot-substring: append after the extension
            newname="${name}${substring}"
            ;;
        *)
            # Insert before the last extension. A leading dot (hidden file)
            # does not count as an extension separator.
            stem="${name#.}"
            lead="${name%"$stem"}"           # "." for hidden files, else ""
            case "$stem" in
                ?*.?*) newname="${lead}${stem%.*}${substring}.${stem##*.}" ;;
                *)     newname="${name}${substring}" ;;
            esac
            ;;
    esac

    target="${dir}${newname}"

    if [ -e "$target" ]; then
        echo "skip: target '$target' already exists" >&2
        status=1
        continue
    fi

    if mv -- "$file" "$target"; then
        echo "renamed: '$file' -> '$target'"
        add_undo "$file" "$target"
    else
        status=1
    fi
done

if [ $renamed -gt 0 ]; then
    echo
    echo "# $renamed file(s) renamed. To undo, run:"
    echo "bash $undo"
else
    echo "# nothing renamed, no undo script created"
fi

exit $status

